"""Build topic pages from FARM's existing glossary; no inventory or analysis scan.

Python 3.10+, standard library only. Run: python tools/build_reference.py [--check]
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'GLOSSARY-CAPABILITIES-MOCKUP.md'
OUTPUT = 'docs/reference/'
NOTICE = '<!-- Generated by tools/build_reference.py from the shared glossary source. Do not edit this page directly. -->'

TOPICS = {
    'containers': ('Containers and constructs', 'Representations, settings, requests and returned results.'),
    'datasets': ('Datasets, grids and units', 'Sources, frame identity, spatial axes and calibration.'),
    'segmentation': ('Segmentation and object identity', 'Category selection and object membership.'),
    'geometry': ('Geometry and sampling supports', 'Boundaries, skeletons, indices and geometric references.'),
    'statistics': ('Scalar sampling and diagnostics', 'Selected values, validity counts and empty selections.'),
    'vectors': ('Vectors, filaments and alignment', 'Components, filament measurements and axial comparisons.'),
    'profiles': ('Profiles and bins', 'Conditional measurements and numerical intervals.'),
    'tracking': ('Tracking and ancestry', 'Detections, trajectory identity and ancestry relationships.'),
    'spectra': ('Spectra and correlations', 'Frequency content, spatial correlation and normalization.'),
    'workflows': ('Workflow results and access', 'The named variables used in workflow 1.'),
}
GROUP_TOPICS = {
    'Containers and structure roles': 'containers',
    'Dataset organization': 'datasets',
    'Segmentation and identity': 'segmentation',
    'Geometry, supports and references': 'geometry',
    'Sampling and measurements': 'statistics',
    'Sampling diagnostics': 'statistics',
    'Workflow 1: recognize the roles in code': 'workflows',
}
VECTOR_TERMS = {'Filament', 'Backbone', 'Principal axes', 'Length', 'Width',
                'Projected extent', 'Axial alignment', 'Vector field', 'Vector component'}
TRACKING_TERMS = {'Detection', 'Trajectory', 'Lineage', 'Ancestry', 'Descendants', 'Split', 'Merge', 'Gap'}
PROFILE_TERMS = {'Conditional profile', 'Bins'}
# Labels describe FARM roles, not every MATLAB container or general concept.
CONSTRUCTS = {'Experiment', 'Data source', 'Grid', 'Query', 'Geometry',
              'Prepared geometry collection', 'Support', 'Payload', 'Manifest',
              'Field', 'Scalar field', 'Vector field', 'Fallback', 'Axial alignment',
              'Lineage', 'Ancestry', 'Descendants', 'Conditional profile', 'Spectrum', 'Correlation'}
INSTANCES = {'experiment', 'objects', 'geometry', 'supports', 'payload', 'manifest'}
RELATED = {
    'containers': ['datasets', 'workflows'], 'datasets': ['segmentation', 'geometry'],
    'segmentation': ['geometry', 'statistics'], 'geometry': ['datasets', 'statistics', 'vectors', 'profiles'],
    'statistics': ['geometry', 'vectors', 'profiles'], 'vectors': ['geometry', 'statistics', 'profiles'],
    'profiles': ['statistics', 'tracking', 'spectra'], 'tracking': ['segmentation', 'profiles', 'workflows'],
    'spectra': ['datasets', 'profiles'], 'workflows': ['containers', 'statistics', 'tracking'],
}


def read(path):
    return path.read_text(encoding='utf-8-sig')


def slug(text):
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


def entries_from_source():
    entries = []
    section = group = ''
    current = None
    complete = False
    for number, raw in enumerate(read(ROOT / SOURCE).splitlines(), 1):
        line = raw.strip()
        if line.startswith('### '):
            group, current = line[4:], None
        elif line.startswith('## '):
            section, current = line[3:].replace(' ', ''), None
        else:
            heading = re.fullmatch(r'\*\*(.+?)\*\*\s+\[(.*)\]', line)
            if heading:
                current = dict(Term=heading[1], Section=section, Group=group, DataType=heading[2],
                               Line=number, Definition=[], Notes=[], Inputs="Inputs: {''}")
                entries.append(current)
                complete = False
            elif current is not None:
                if not line:
                    if current['Definition']:
                        complete = True
                    if current['Notes'] and current['Notes'][-1] != '':
                        current['Notes'].append('')
                elif line.startswith('Inputs:'):
                    current['Inputs'] = line
                    complete = True
                elif complete:
                    current['Notes'].append(raw.rstrip())
                else:
                    current['Definition'].append(raw.rstrip())

    keys = [(e['Section'], e['Term']) for e in entries]
    if len(keys) != len(set(keys)):
        raise ValueError('Duplicate term within a source section')
    for entry in entries:
        term = entry['Term']
        if term in VECTOR_TERMS:
            topic = 'vectors'
        elif entry['Group'] == 'Tracking and field analysis':
            topic = 'tracking' if term in TRACKING_TERMS else ('profiles' if term in PROFILE_TERMS else 'spectra')
        else:
            topic = GROUP_TOPICS[entry['Group']]
        entry.update(Topic=topic, Anchor=slug(entry['Section']+'-'+entry['Group']+'-'+term))
        entry['Role'] = 'Construct' if term in CONSTRUCTS else ('Construct instance' if term in INSTANCES else '')
        entry['Definition'] = '\n'.join(entry['Definition']).strip()
        entry['Notes'] = '\n'.join(entry['Notes']).strip()
        if not entry['Definition'] or entry['Section'] not in ('Glossary', 'DataDictionary'):
            raise ValueError('Incomplete source entry: '+term)
    if len({e['Anchor'] for e in entries}) != len(entries):
        raise ValueError('Duplicate topic-page anchor')
    if not entries:
        raise ValueError('No entries found')
    return entries


def build():
    entries = entries_from_source()
    outputs = {}
    index = [NOTICE, '# Glossary and Data Dictionary',
             'Choose a topic below. Concepts and named quantities are kept together, with their '
             'Glossary or DataDictionary classification shown. Short definitions are visible; '
             'input layouts, lookup commands and interpretation notes are expandable.',
             'These pages present the **current documented entries**. They do not claim to cover '
             'every public function or returned quantity. The full function/test inventory is deferred '
             'until the remaining functionality has been evaluated.',
             'Definitions have one editable source: the [shared glossary](../../'+SOURCE+'). '
             'Each entry has one topic-page location; related pages link to it. Rebuild these views '
             'after editing the source. MATLAB reads that same source directly.',
             '| Topic | Entries | Contents |\n| --- | ---: | --- |\n' + '\n'.join(
                 f'| [{title}]({topic}.md) | {sum(e["Topic"]==topic for e in entries)} | {description} |'
                 for topic, (title, description) in TOPICS.items()),
             '## Find an entry',
             'Use the [alphabetical index](terms.md), browser Find on a topic page, or '
             '`farmGlossary("search", "distance")` in MATLAB. '
             '[MATLAB lookup and getters](../MATLAB-GLOSSARY.md) explain section filters and exact spelling.',
             f'The current source contains **{len(entries)} entries**, including '
             f'**{sum(e["Section"]=="DataDictionary" for e in entries)} Data Dictionary quantities**. '
             'The dictionary currently covers sampling diagnostics; it is not a complete list of requestable statistics.',
             '## Reading the labels',
             '**Construct** identifies an item with a defined FARM role and documented representation. '
             'A **construct instance** is a workflow variable holding one of those items. '
             'A container type such as struct or table is not automatically a construct. '
             'These labels describe roles and do not change the MATLAB entry schema.',
             '**Inputs** reproduces the source layout. Some layouts describe generated results; read '
             'the interpretation notes before treating fields as constructor arguments. '
             'An entry with no documented layout displays `Inputs: {\'\'}`.',
             'Mesh and sheet entries remain available to interpret historical material. Those operations '
             'are deferred, as are ND2 and the two historical estimators. A definition does not establish release support.']
    outputs[OUTPUT+'README.md'] = '\n\n'.join(index)+'\n'
    alphabetical = [NOTICE, '# Alphabetical entry index', '[Scientific topics](README.md)',
                    '| Entry | Classification | Topic |\n| --- | --- | --- |\n'+'\n'.join(
                        f'| [{e["Term"]}]({e["Topic"]}.md#{e["Anchor"]}) | {e["Section"]} | {TOPICS[e["Topic"]][0]} |'
                        for e in sorted(entries, key=lambda e:(e['Term'].lower(), e['Term'])))]
    outputs[OUTPUT+'terms.md'] = '\n\n'.join(alphabetical)+'\n'
    by_term = {e['Term']:e for e in entries}
    for topic, (title, description) in TOPICS.items():
        selected = [e for e in entries if e['Topic'] == topic]
        page = [NOTICE, '# '+title, description,
                '[All topics](README.md) · [Alphabetical index](terms.md) · [MATLAB lookup](../MATLAB-GLOSSARY.md)',
                ' · '.join(f'[{e["Term"]}](#{e["Anchor"]})' for e in selected)]
        if topic == 'statistics':
            page += ['## Access the diagnostic columns',
                     'Run `farmSetup` from the repository root first. This small example samples '
                     'every location in an array and requests a mean and finite-value count. '
                     'The diagnostic columns are returned alongside those requested statistics.',
                     '```matlab\nsignal = [0 NaN 2; Inf 4 -Inf];\n'
                     'results = farmQueryField(signal, true(size(signal)), {\'Mean\', \'Count\'}, ...\n'
                     '    struct(\'FieldName\', \'Signal\'));\n'
                     'results.Signal_Mean           % 2\nresults.Signal_Count          % 3 finite values\n'
                     'results.Signal_SelectedCount  % 6 selected locations\n'
                     'results.Signal_FiniteCount    % 3\n```',
                     '`farmQueryField` uses `<FieldName>_<quantity>` column names. `farmQueryFrame` '
                     'uses the query name as the prefix. Vector components use '
                     '`<FieldName>_<ComponentName>_<quantity>`. No population or ancestry reduction is implied.']
        if topic == 'profiles':
            page += ['Population summaries and independent per-object distance profiles require explicit '
                     'grouping and scientific choices. This page documents current concepts; it does not '
                     'introduce an automatic ancestry, weighting or per-object distance policy.']
        for e in selected:
            label = f'**{e["Section"]} / {e["Group"]}**'
            if e['Role']:
                label += ' · **'+e['Role']+'**'
            page += [f'<a id="{e["Anchor"]}"></a>', '## '+e['Term'], label,
                     '['+e['DataType']+']', e['Definition'],
                     '<details>\n<summary>Input layout and MATLAB lookup</summary>\n',
                     '```text\n'+e['Inputs'].replace('`', '').replace('\\*', '*')+'\n```',
                     '```matlab\nentry = farmGlossary('+json.dumps(e['Term'])+
                     ', "Section", '+json.dumps(e['Section'])+');\n```', '\n</details>']
            if e['Notes']:
                page += ['<details>\n<summary>Interpretation and scope</summary>\n', e['Notes'], '\n</details>']
            if e['Section'] == 'DataDictionary':
                page += ['<details>\n<summary>Access in returned data</summary>\n',
                         'After a scalar query with `FieldName = \'Signal\'`:',
                         f'```matlab\nvalue = results.Signal_{e["Term"]};\n```',
                         'For query/component prefixes, see the example at the top of this page. '
                         'These are generated values, not additional inputs.', '\n</details>']
            if e['Term'] in ('Sheet', 'Centered surface', 'Mesh'):
                page.append('**Release scope:** mesh/sheet operations are deferred pending study.')
            page.append(f'[Source entry](../../{SOURCE}?plain=1#L{e["Line"]})')
        related = RELATED[topic]
        page += ['## Related topics', ' · '.join(f'[{TOPICS[t][0]}]({t}.md)' for t in related)]
        # Give each related topic a concrete entry destination as well as its page link.
        related_entries = {'containers':['Experiment','Query'], 'datasets':['Grid','Coordinates'],
                           'segmentation':['Support','Geometry'], 'geometry':['Query','Conditional profile'],
                           'statistics':['Support','Vector field','Conditional profile'],
                           'vectors':['Geometry','Reference'], 'profiles':['SelectedCount','Ancestry'],
                           'tracking':['ID group','Conditional profile'], 'spectra':['Grid','Bins'],
                           'workflows':['Experiment','Geometry','Query']}[topic]
        page.append('Related entries: '+' · '.join(
            f'[{term}]({by_term[term]["Topic"]}.md#{by_term[term]["Anchor"]})' for term in related_entries))
        outputs[OUTPUT+topic+'.md'] = '\n\n'.join(page).rstrip()+'\n'
    rows = [{key:e[key] for key in ('Term','Section','Group','DataType','Topic','Anchor','Role','Line')} for e in entries]
    stream = io.StringIO(newline='')
    writer = csv.DictWriter(stream, fieldnames=list(rows[0]), lineterminator='\n')
    writer.writeheader()
    writer.writerows(rows)
    outputs[OUTPUT+'ENTRIES.csv'] = stream.getvalue()
    return outputs, entries


def validate(outputs, entries):
    locations = []
    for filename, text in outputs.items():
        if not filename.endswith('.md'):
            continue
        if text.count('<details>') != text.count('</details>'):
            raise ValueError('Unbalanced expandable details in '+filename)
        if len(re.findall(r'^```', text, re.M)) % 2:
            raise ValueError('Unbalanced code block in '+filename)
        locations += re.findall(r'<a id="([^"]+)"></a>', text)
        for match in re.finditer(r'(?<!!)\[[^\]\n]+\]\(([^\n)]+)\)', text):
            target = match[1]
            if target.startswith(('http://','https://','mailto:')):
                continue
            filepart, _, fragment = target.partition('#')
            filepart = filepart.partition('?')[0]
            path = ((ROOT / filename).parent / filepart).resolve() if filepart else ROOT / filename
            key = path.relative_to(ROOT).as_posix()
            contents = outputs.get(key)
            if contents is None:
                if not path.is_file():
                    raise ValueError(f'Broken link in {filename}: {target}')
                contents = read(path)
            if fragment:
                if re.fullmatch(r'L\d+', fragment):
                    if int(fragment[1:]) > len(contents.splitlines()):
                        raise ValueError('Source line outside document: '+target)
                else:
                    anchors = set(re.findall(r'<a id="([^"]+)"></a>', contents))
                    anchors.update(slug(h) for h in re.findall(r'^#+ (.+)$', contents, re.M))
                    if fragment not in anchors:
                        raise ValueError(f'Broken anchor in {filename}: {target}')
    if sorted(locations) != sorted(e['Anchor'] for e in entries):
        raise ValueError('Every source entry must have exactly one topic-page location')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated pages are stale; write nothing')
    args = parser.parse_args()
    outputs, entries = build()
    validate(outputs, entries)
    stale = []
    for filename, text in outputs.items():
        path = ROOT / filename
        if args.check:
            if not path.is_file() or read(path) != text:
                stale.append(filename)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8', newline='\n')
    if stale:
        raise SystemExit('Stale reference pages; rebuild:\n'+'\n'.join(stale))
    print(f'{"Checked" if args.check else "Wrote"} {len(outputs)} files for {len(entries)} entries; '
          'links, anchors and expandable sections valid. No public/test inventory generated.', flush=True)


if __name__ == '__main__':
    main()
