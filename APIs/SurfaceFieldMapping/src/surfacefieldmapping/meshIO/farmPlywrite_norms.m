function farmPlywrite_norms(filename,faces,verts,vertnorms)
% plywrite(filename,faces,verts)
% Rewrite from 2015 Ahmet Cecen.
% Write vertex, face, and vertex NORMAL data to ply format.
% Will write a face vertex mesh data in ply format.
% faces -> polygonal descriptions in terms of vertex indices
% verts -> list of vertex coordinate triplets
% vertnorms -> vertex coordinate triplets of vertex normals

% Open file

fileID = fopen(filename,'w');

% Mesh from verts and faces
if nargin == 3
    
    % Insert Header
    fprintf(fileID, ...
        ['ply\n', ...
        'format ascii 1.0\n', ...
        'element vertex %u\n', ...
        'property float32 x\n', ...
        'property float32 y\n', ...
        'property float32 z\n', ...
        'element face %u\n', ...
        'property list uint8 int32 vertex_indices\n', ...
        'end_header\n'], ...
        length(verts),length(faces));

    % Insert Colored Vertices
    for vertInd = 1:length(verts)
        fprintf(fileID, ...
            ['%.6f ', ...
            '%.6f ', ...
            '%.6f\n'], ...
            verts(vertInd,1),verts(vertInd,2),verts(vertInd,3));
    end

    % Insert Faces
    dlmwrite(filename,[size(faces,2)*ones(length(faces),1),faces-1],'-append','delimiter',' ','precision',10);

% Mesh from faces and vertices with vertex normals
elseif nargin == 4

     % Insert Header
    fprintf(fileID, ...
        ['ply\n', ...
        'format ascii 1.0\n', ...
        'element vertex %u\n', ...
        'property float32 x\n', ...
        'property float32 y\n', ...
        'property float32 z\n', ...
        'property float32 nx\n', ...
        'property float32 ny\n', ...
        'property float32 nz\n', ...
        'element face %u\n', ...
        'property list uint8 int32 vertex_indices\n', ...
        'end_header\n'], ...
        length(verts),length(faces));

    % Insert vertices with normals
    for vertInd = 1:length(verts)
        fprintf(fileID, ...
            ['%.6f ', '%.6f ', '%.6f ', ...
            '%.6f ', '%.6f ', '%.6f\n'], ...
            verts(vertInd,1),verts(vertInd,2),verts(vertInd,3),...
            vertnorms(vertInd,1),vertnorms(vertInd,2),vertnorms(vertInd,3));
    end

    % Insert Faces
    dlmwrite(filename,[size(faces,2)*ones(length(faces),1),faces-1],'-append','delimiter',' ','precision',10);

end